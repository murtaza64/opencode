import { createRequire } from "node:module"
import { startAttentionPreview } from "./attention-preview.mjs"

const { chromium, expect } = createRequire(new URL("../../app/package.json", import.meta.url))("@playwright/test")
const preview = await startAttentionPreview()
const browser = await chromium.launch({ channel: "chrome", headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
await page.route("**/*", route => new URL(route.request().url()).origin === preview.origin ? route.continue() : route.abort())
const errors = []
page.on("pageerror", error => errors.push(error.message))
const sidebar = page.locator(".sidebar")
const pinned = () => sidebar.locator(".pinned-section")
try {
  await page.goto(preview.url)
  await sidebar.locator(".cloud-discovery summary").click()
  await expect(sidebar.locator(".cloud-discovery")).toContainText("cloud-review")
  await sidebar.getByRole("button", { name: "Pin cloud agent cloud-review", exact: true }).click()
  await expect(pinned().locator(".nav-item")).toHaveCount(2)
  const link = pinned().locator("a.cloud-nav")
  await expect(link.locator("[aria-label='Cloud agent']")).toBeVisible()
  expect(await link.getAttribute("href")).toContain("/cloud?es=fixture&lane=cloud-review&owner=wingman%3Afixture-task")
  expect(preview.ledger.transcriptCalls).toBe(0)
  await pinned().getByRole("link", { name: /Composer fixture/ }).click()
  await page.getByRole("textbox", { name: "Message", exact: true }).fill("Keep this local draft while inspecting cloud work")
  await pinned().locator("a.cloud-nav").focus()
  await page.keyboard.press("Enter")
  await expect(page.getByRole("heading", { name: "Cloud agent", exact: true })).toBeVisible()
  await expect(page).toHaveURL(/\/cloud\?es=fixture/)
  expect(preview.ledger.transcriptCalls).toBe(0)
  const details = page.getByRole("region", { name: "Cloud agent details", exact: true })
  await expect(details).toContainText("0.42")
  await expect(details.getByRole("link", { name: "Runtime workflow" })).toHaveAttribute("href", "https://cloud.temporal.io/namespaces/fixture/workflows/fixture")
  await details.getByRole("button", { name: "Load transcript", exact: true }).click()
  await expect(details).toContainText("Synthetic cloud transcript")
  expect(preview.ledger.transcriptCalls).toBe(1)
  await page.getByRole("button", { name: "Refresh cloud source", exact: true }).click()
  await expect(details).toContainText("Synthetic cloud transcript")
  expect(preview.ledger.transcriptCalls).toBe(1)
  preview.ledger.cloudStatus = 404
  await page.getByRole("button", { name: "Refresh cloud source", exact: true }).click()
  await expect(details).toContainText("last-known snapshot retained")
  await expect(pinned().locator("a.cloud-nav")).toBeVisible()
  await expect(pinned().locator("a.cloud-nav")).toHaveAttribute("title", /source unavailable/)
  preview.ledger.cloudStatus = 200
  await page.getByRole("button", { name: "Refresh cloud source", exact: true }).click()
  await expect(details).not.toContainText("source unavailable")
  await page.locator(".es-switcher").selectOption("other")
  await expect(pinned().locator("a.cloud-nav")).toBeVisible()
  await page.locator(".es-switcher").selectOption("__all__")
  await pinned().getByRole("link", { name: /Composer fixture/ }).click()
  await expect(page.getByRole("textbox", { name: "Message", exact: true })).toHaveValue("Keep this local draft while inspecting cloud work")
  await page.reload()
  await expect(pinned().locator(".nav-item")).toHaveCount(2)
  await page.evaluate(() => { document.documentElement.dir = "rtl" })
  await page.setViewportSize({ width: 760, height: 1000 })
  await pinned().locator("a.cloud-nav").click()
  await expect(details).toBeVisible()
  expect(await details.evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true)
  await page.getByRole("button", { name: "Collapse sidebar", exact: true }).click()
  await expect(page.locator(".sidebar-mini .cloud-runtime-icon")).toBeVisible()
  expect(preview.fixture.calls.filter(call => !["GET", "HEAD", "OPTIONS"].includes(call.method))).toEqual([])
  expect(errors).toEqual([])
  console.log("PASS cloud sidebar: cloud icon/local+workflow pins, exact cloud route, keyboard navigation, shared source/refresh, missing API recovery, cross-project pin persistence, on-demand transcript, draft return/reload, collapsed RTL, no runtime writes")
} finally { await browser.close(); await preview.close() }
