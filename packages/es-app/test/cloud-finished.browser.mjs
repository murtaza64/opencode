import { createRequire } from "node:module"
import { startAttentionPreview } from "./attention-preview.mjs"

const { chromium, expect } = createRequire(new URL("../../app/package.json", import.meta.url))("@playwright/test")
const preview = await startAttentionPreview()
preview.ledger.cloudLanes = [{ ...preview.ledger.cloudLanes[0], lane: "ended-review", owner: "wingman:ended-review-task", status: "parked", "wingman-status": "ended", activity: "Completed fixture awaiting PR review", "wingman-prs": "https://github.com/example/repo/pull/1103" }]
const browser = await chromium.launch({ channel: "chrome", headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
await page.route("**/*", route => new URL(route.request().url()).origin === preview.origin ? route.continue() : route.abort())
const discovery = page.locator(".sidebar .cloud-discovery")
try {
  await page.goto(preview.url)
  await page.locator(".sidebar .pinned-section").getByRole("link", { name: /Composer fixture/ }).click()
  const draft = page.getByRole("textbox", { name: "Message", exact: true })
  await draft.fill("Keep my local draft while finding completed cloud work")
  await discovery.locator("summary").click()
  await expect(discovery.locator(".cloud-sidebar-source")).not.toContainText("Active tasks only")
  await expect(discovery.getByRole("button", { name: "Pin cloud agent ended-review", exact: true })).toHaveCount(0)
  await discovery.getByRole("checkbox", { name: "Include finished", exact: true }).check()
  await expect(discovery.getByRole("checkbox", { name: "Include finished", exact: true })).toBeChecked()
  await expect(discovery).toContainText("ended")
  await discovery.getByRole("button", { name: "Pin cloud agent ended-review", exact: true }).click()
  await page.locator('.pinned-section [data-cloud-owner="wingman:ended-review-task"] a').click()
  const details = page.getByRole("region", { name: "Cloud agent details", exact: true })
  await expect(details).toContainText("Completed fixture awaiting PR review")
  await expect(details.getByRole("link", { name: /PR .*1103/ })).toHaveAttribute("href", "https://github.com/example/repo/pull/1103")
  await page.locator(".sidebar .pinned-section").getByRole("link", { name: /Composer fixture/ }).click()
  await expect(draft).toHaveValue("Keep my local draft while finding completed cloud work")
  await page.locator(".sidebar a.board-link[href='/']").click()
  await expect(page.getByRole("heading", { name: "Needs you 3", exact: true })).toBeVisible()
  await page.getByRole("complementary", { name: "Desk queue" }).getByRole("button", { name: /^Agents/ }).click()
  const cloud = page.getByRole("region", { name: "Cloud agents", exact: true })
  await cloud.getByRole("button", { name: "Unpin", exact: true }).click()
  await cloud.getByText("Other cloud tasks (1)", { exact: true }).click()
  await expect(cloud.getByRole("checkbox", { name: "Include finished", exact: true })).toBeChecked()
  await cloud.getByRole("checkbox", { name: "Include finished", exact: true }).uncheck()
  await expect(cloud).toContainText("Active tasks only")
  await expect(cloud.getByRole("button", { name: "Pin", exact: true })).toHaveCount(0)
  await expect(discovery.getByRole("checkbox", { name: "Include finished", exact: true })).not.toBeChecked()
  expect(preview.fixture.calls.filter(call => !["GET", "HEAD", "OPTIONS"].includes(call.method))).toEqual([])
  console.log("PASS finished cloud discovery: active-only default, explicit shared Include finished, ended/parked PR1103 fixture discover/pin, local draft preserved, no automatic pins/attention/runtime writes")
} finally { await browser.close(); await preview.close() }
